const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const resolve = Module._resolveFilename;
Module._resolveFilename = function(name,parent,...rest) { return resolve.call(this,name.startsWith('@/') ? path.join(__dirname,'../src',name.slice(2)) : name,parent,...rest); };
require.extensions['.ts'] = (module,file) => module._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,file);
const { SPORTS, sportRules, validateSport, setSportCatalog, getSport } = require('../src/constants/sports.ts');
const { buildSportScoreboard } = require('../src/lib/sportScoreboard.ts');
const { segmentCanFinish, scoreboardTotal } = require('../src/lib/growth.ts');
const { computePlayerActivitySummary } = require('../src/lib/performance.ts');
const defaults = SPORTS.map(s=>({...s,active:true,revision:1,rules:sportRules(s)}));
assert(defaults.every(validateSport));
const sport = {...defaults[1],id:'queimada',label:'Queimada',hasGoalkeeper:false,suggestedTeamSize:5,rules:{...defaults[1].rules,mode:'total',periods:1,targetPoints:null,winByTwo:false,setsToWin:null,scoreValues:[1,2]}};
assert(validateSport(sport));
assert(!validateSport({...sport,color:'#fff'}));
assert(!validateSport({...sport,rules:{...sport.rules,scoreValues:[2]}}));
assert(!validateSport({...sport,rules:{...sport.rules,periods:0}}));
setSportCatalog([...defaults,sport]);
assert.equal(getSport('queimada').hasGoalkeeper,false);
const board = buildSportScoreboard(sport,{id:'b',segmentId:'s',createdBy:'p',title:'Bairro',homeName:'A',awayName:'B'});
assert.equal(board.unit,'points'); assert.equal(board.maxSegments,1); assert.deepEqual(board.scoreValues,[1,2]);
setSportCatalog([...defaults,{...sport,rules:{...sport.rules,scoreValues:[1],periodMinutes:30}}]);
assert.deepEqual(board.scoreValues,[1,2]); assert.equal(board.periodMinutes,10);
assert(!segmentCanFinish({home:21,away:20},21,true));
assert(segmentCanFinish({home:22,away:20},21,true));
const volley = buildSportScoreboard(defaults[1],{id:'v',segmentId:'v1',createdBy:'p',title:'V',homeName:'A',awayName:'B'});
volley.segments[0] = {...volley.segments[0],home:21,away:18,finished:true};
assert.deepEqual(scoreboardTotal(volley),{home:1,away:0});
const stats = computePlayerActivitySummary('p',[{id:'g',status:'finished'}],[{playerId:'p',gameId:'elsewhere',noShow:true},{playerId:'p',gameId:'g',status:'confirmed',noShow:false}]);
assert.equal(stats.noShows,0); assert.equal(stats.gamesPlayed,1);
console.log('PASS: sport validation, goalkeeper rules, score modes/increments, frozen rule snapshots, set margin and scoped personal stats.');
